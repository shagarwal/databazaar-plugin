"""World Bank Indicators API adapter.

The World Bank API is the engine behind ~30% of databazaar's existing
country-panel listings. No auth required.

Pattern: extract indicator hint from request → look up indicator code →
fetch full panel for all countries × all years → return long-format rows.

v0.2: supports 12 hand-mapped indicators (the most common in the catalog).
Future v0.3: full indicator search via /indicator endpoint.
"""
from __future__ import annotations
import json, urllib.request, urllib.parse
from datetime import datetime, timezone

API = "https://api.worldbank.org/v2"

# Hand-mapped indicators based on databazaar catalog patterns
INDICATORS = {
    "gdp per capita": ("NY.GDP.PCAP.CD", "GDP per capita (current US$)"),
    "gdp": ("NY.GDP.MKTP.CD", "GDP (current US$)"),
    "population": ("SP.POP.TOTL", "Population, total"),
    "life expectancy": ("SP.DYN.LE00.IN", "Life expectancy at birth, total (years)"),
    "unemployment": ("SL.UEM.TOTL.ZS", "Unemployment, total (% of labor force)"),
    "inflation": ("FP.CPI.TOTL.ZG", "Inflation, consumer prices (annual %)"),
    "literacy": ("SE.ADT.LITR.ZS", "Literacy rate, adult total (% of people 15+)"),
    "co2 emissions": ("EN.GHG.ALL.PC.CE.AR5", "Total greenhouse gas emissions per capita (t CO2e)"),
    "internet users": ("IT.NET.USER.ZS", "Individuals using the Internet (% of population)"),
    "labor force": ("SL.TLF.TOTL.IN", "Labor force, total"),
    "school enrollment": ("SE.PRM.ENRR", "School enrollment, primary (% gross)"),
    "health expenditure": ("SH.XPD.CHEX.GD.ZS", "Current health expenditure (% of GDP)"),
}


def _ts() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _get_json(url: str) -> object:
    req = urllib.request.Request(
        url, headers={"User-Agent": "databazaar-skill/0.2.0"}
    )
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.loads(r.read())


def _detect_indicator(request: str) -> tuple[str, str] | None:
    t = request.lower()
    for keyword, (code, name) in INDICATORS.items():
        if keyword in t:
            return code, name
    return None


def can_handle(request: str) -> float:
    t = request.lower()
    indicator = _detect_indicator(request)
    country_signals = ["country", "countries", "by country", "panel", "global",
                       "world", "international", "by year", "annual"]
    if indicator and any(s in t for s in country_signals):
        return 0.95
    if indicator:
        return 0.7
    if any(s in t for s in country_signals):
        return 0.4
    return 0.0


def fetch(request: str) -> dict:
    indicator = _detect_indicator(request)
    if not indicator:
        return {
            "rows": [],
            "schema": {"title": request, "columns": []},
            "sources": [],
            "gaps": "No World Bank indicator matched the request. v0.2 supports 12 hand-mapped indicators — see scripts/adapters/world_bank.py.",
        }

    code, name = indicator
    retrieved = _ts()
    url = f"{API}/country/all/indicator/{code}?format=json&per_page=20000"
    try:
        resp = _get_json(url)
    except Exception as e:
        return {
            "rows": [],
            "schema": {"title": name, "columns": []},
            "sources": [],
            "gaps": f"World Bank API request failed: {e}",
        }

    if not isinstance(resp, list) or len(resp) < 2:
        return {
            "rows": [],
            "schema": {"title": name, "columns": []},
            "sources": [],
            "gaps": "World Bank API returned unexpected response shape.",
        }

    raw = resp[1] or []
    rows = []
    for r in raw:
        if r.get("value") is None:
            continue
        rows.append({
            "country_code": r["country"]["id"],
            "country_name": r["country"]["value"],
            "indicator_code": code,
            "indicator_name": name,
            "year": r["date"],
            "value": r["value"],
            "_source": f"worldbank:{code}",
            "_retrieved_at": retrieved,
        })

    schema = {
        "title": f"{name} — World Bank panel",
        "description": (
            f"World Bank indicator {code} ({name}) for all countries and "
            "available years. Long-format. Generated by the databazaar skill."
        ),
        "category": "social",  # most WB indicators map here; refine via taxonomy.md
        "tags": ["world-bank", "panel-data", "country-level", "time-series", code.lower()],
        "columns": [
            {"name": "country_code", "type": "string", "description": "ISO 3-letter country code (or aggregate code)"},
            {"name": "country_name", "type": "string", "description": "Country name as published by WB"},
            {"name": "indicator_code", "type": "string", "description": f"Always '{code}' for this dataset"},
            {"name": "indicator_name", "type": "string", "description": f"Always '{name}'"},
            {"name": "year", "type": "string", "description": "4-digit year"},
            {"name": "value", "type": "number", "description": "Indicator value"},
        ],
    }
    sources = [{
        "name": f"World Bank Indicators API — {code}",
        "url": url,
        "license": "CC BY-4.0",
        "retrieved_at": retrieved,
    }]
    return {
        "rows": rows,
        "schema": schema,
        "sources": sources,
        "intended_use": "Country-panel analysis — comparable across countries and years. Note: WB also publishes regional aggregates (codes like WLD, EUU); filter on country_code if you only want sovereign nations.",
    }
